// 05-styles/13-page-fit.js — документ ровно по экрану, без прокрутки страницы.
const STYLE_PAGE_FIT = `@media (max-width: 1023px) {
    /* Прокручиваться должен только список сообщений, а не страница. Пока высота
       документа совпадала с экраном случайно (её задавал кадр), на телефоне
       палец утаскивал вниз весь интерфейс вместе с шапкой и полем ввода — это и
       читается как «страница длиннее экрана». */
    html, body {
      height: 100% !important;
      max-height: 100% !important;
      overflow: hidden !important;
      /* Отскок за границы и «потянуть, чтобы обновить»: в чате оба срабатывают
         от любого свайпа вниз и выглядят как прокрутка самой страницы. */
      overscroll-behavior: none;
    }
    /* 100dvh — видимая высота вместе с адресной строкой; 100vh её не учитывает
       и оставляет ровно ту прокрутку, ради которой всё это написано. Браузеры
       без dvh отбрасывают это правило и остаются с height: 100% выше. */
    body {
      height: 100dvh !important;
    }
    /* Кадр занимает ту же высоту, что и документ. Клавиатура по-прежнему
       подставляет своё значение переменной из JS. */
    [class$='_frame'] {
      height: var(${FRAME_HEIGHT_VAR}, 100%) !important;
      max-height: var(${FRAME_HEIGHT_VAR}, 100%) !important;
      overflow: hidden !important;
    }
  }`
