/** Ширина, до которой harness считает раскладку узкой. */
const NARROW_MAX_PX = 1023

/**
 * Сейчас узкий экран (телефон)?
 *
 * Этим вопросом закрывается КАЖДАЯ часть слоя, которая меняет поведение, а не
 * только внешний вид: логика панели, обработчики нажатий, слот в шапке, замер
 * полосы статистики. Слой существует ради телефона, а на широком экране панель
 * harness и так стоит в раскладке — и тогда тот же код начинает спорить с ней.
 *
 * @returns true, если раскладка узкая.
 */
function isNarrow() {
  return window.matchMedia(`(max-width: ${NARROW_MAX_PX}px)`).matches
}

